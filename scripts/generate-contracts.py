#!/usr/bin/env python3
"""Generate Rust serde DTOs and TypeScript DTOs from the same v1 JSON schema."""
import json, re, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
schema=json.loads((ROOT/'contracts/v1.schema.json').read_text())
defs=schema['$defs']
def snake(name): return re.sub(r'(?<!^)(?=[A-Z])','_',name).lower()
def nullable(prop):
    return isinstance(prop.get('type'),list) and 'null' in prop['type']
def nonnull(prop):
    p=dict(prop)
    if isinstance(p.get('type'),list): p['type']=next(x for x in p['type'] if x!='null')
    if 'enum' in p: p['enum']=[value for value in p['enum'] if value is not None]
    return p
def rt(prop):
    if nullable(prop): return f'Option<{rt(nonnull(prop))}>'
    if '$ref' in prop: return prop['$ref'].split('/')[-1]
    if prop.get('type')=='array': return f'Vec<{rt(prop["items"])}>'
    return prop.get('x-rust-type',{'string':'String','integer':'u64','boolean':'bool'}[prop['type']])
def tt(prop):
    if nullable(prop): return tt(nonnull(prop))+' | null'
    if '$ref' in prop:return prop['$ref'].split('/')[-1]
    if 'enum' in prop:return ' | '.join(json.dumps(v) for v in prop['enum'])
    if prop.get('type')=='array':return f'Array<{tt(prop["items"])}>'
    return {'string':'string','integer':'number','boolean':'boolean'}[prop['type']]
rust=['// Generated by scripts/generate-contracts.py. Do not edit.','use serde::{Deserialize, Serialize};']
ts=['// Generated by scripts/generate-contracts.py. Do not edit.']
for name,definition in defs.items():
    if definition['type']!='object':
        rust.append(f'pub type {name} = {rt(definition)};')
        ts.append(f'export type {name} = {tt(definition)};')
        continue
    rust+=['#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]','#[serde(rename_all = "camelCase")]',f'pub struct {name} {{']
    ts.append(f'export type {name} = {{')
    for field,prop in definition['properties'].items():
        if 'default' in prop: rust.append('    #[serde(default)]')
        rust.append(f'    pub {snake(field)}: {rt(prop)},')
        ts.append(f'  {field}: {tt(prop)};')
    rust.append('}')
    ts.append('};')
outputs={ROOT/'crates/writing-core/src/models.rs':'\n'.join(rust)+'\n',ROOT/'src/generated/dto.ts':'\n'.join(ts)+'\n'}
for path,content in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text()!=content: sys.exit(f'Contract output is stale: {path}')
    else:path.write_text(content)
